import os
import numpy as np

MODEL_PATH = "../results/xor_model.npz"
OUTPUT_PATH = "../pico/model_params.py"

if not os.path.exists(MODEL_PATH):
    raise FileNotFoundError(
        "Model file not found. Run train.py first from the training directory."
    )

data = np.load(MODEL_PATH)

with open(OUTPUT_PATH, "w", encoding="utf-8") as f:
    f.write("# Generated by training/export.py. Do not edit manually.\n")
    f.write("W1 = " + repr(data["W1"].tolist()) + "\n")
    f.write("b1 = " + repr(data["b1"].tolist()) + "\n")
    f.write("W2 = " + repr(data["W2"].tolist()) + "\n")
    f.write("b2 = " + repr(data["b2"].tolist()) + "\n")

print("Exported model parameters to pico/model_params.py")
